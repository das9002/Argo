-- 1. ELIMINACIÓN PREVENTIVA DE TABLAS Y SECUENCIAS (CASCADE)
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE detalle_facturas CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE facturas CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE productos CASCADE CONSTRAINTS';
    EXECUTE IMMEDIATE 'DROP TABLE clientes CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        NULL; -- Ignorar si no existen aún
END;
/

-- 2. TABLA 1: CLIENTES
-- Registra a los compradores mediante su documento fiscal único (DUI/NIT)
CREATE TABLE clientes (
    cliente_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dui_nit             VARCHAR2(20) NOT NULL UNIQUE,
    nombre_razon_social VARCHAR2(150) NOT NULL,
    telefono            VARCHAR2(25),
    email               VARCHAR2(100),
    direccion           VARCHAR2(250),
    tipo_contribuyente  VARCHAR2(50) DEFAULT 'Consumidor Final' CHECK (tipo_contribuyente IN ('Consumidor Final', 'Crédito Fiscal (CCF)', 'Gran Contribuyente')),
    nrc                 VARCHAR2(20), -- Número de Registro de Contribuyente (IVA)
    limite_credito      NUMBER(12,2) DEFAULT 0.00,
    saldo_pendiente     NUMBER(12,2) DEFAULT 0.00,
    fecha_registro      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

COMMENT ON TABLE clientes IS 'Maestro de compradores, receptores DTE y perfiles de crédito comercial';
COMMENT ON COLUMN clientes.dui_nit IS 'Documento de Identidad Oficial en El Salvador (DUI o NIT)';

-- 3. TABLA 2: PRODUCTOS
-- Controla el inventario y los precios base de los artículos
CREATE TABLE productos (
    producto_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku                 VARCHAR2(40) NOT NULL UNIQUE,
    nombre              VARCHAR2(150) NOT NULL,
    categoria           VARCHAR2(60) NOT NULL,
    precio_costo        NUMBER(10,2) NOT NULL,
    margen_ganancia     NUMBER(5,2) DEFAULT 25.00 NOT NULL,
    precio_venta        NUMBER(10,2) NOT NULL, -- Precio al público con IVA 13% incluido
    stock               NUMBER(9) DEFAULT 0 NOT NULL,
    stock_minimo        NUMBER(9) DEFAULT 5 NOT NULL,
    imagen_url          VARCHAR2(350),
    fecha_actualizacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_stock_positivo CHECK (stock >= 0)
);

COMMENT ON TABLE productos IS 'Catálogo e inventario en tiempo real con alertas de stock mínimo';
COMMENT ON COLUMN productos.precio_venta IS 'Precio final de venta (incluye 13% IVA)';

-- 4. TABLA 3: FACTURAS
-- Encabezado de la venta fiscal y comunicación con el Ministerio de Hacienda (DTE)
CREATE TABLE facturas (
    factura_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_dte          VARCHAR2(35) NOT NULL UNIQUE, -- Ej: DTE-01-M001-00004928
    codigo_generacion   VARCHAR2(40) NOT NULL UNIQUE, -- UUID según normativa DTE El Salvador
    sello_recepcion_mh  VARCHAR2(80) NOT NULL,        -- Sello criptográfico retornado por Hacienda
    fecha_hora          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    cliente_id          NUMBER NOT NULL,
    tipo_dte            VARCHAR2(25) DEFAULT 'Factura (01)' NOT NULL, -- 'Factura (01)' o 'CCF (03)'
    subtotal_neto       NUMBER(12,2) NOT NULL,       -- Base gravable sin IVA
    iva_monto           NUMBER(12,2) NOT NULL,       -- Débito Fiscal retenido (13%)
    total_pagado        NUMBER(12,2) NOT NULL,       -- Subtotal + IVA
    metodo_pago         VARCHAR2(50) NOT NULL,       -- Efectivo, Tarjeta, Chivo Wallet, Transferencia
    referencia_pago     VARCHAR2(100),               -- Token de pasarela Stripe/Pagadito o No. Autorización
    estado_hacienda     VARCHAR2(30) DEFAULT 'Transmitido con Éxito' NOT NULL,
    cajero_responsable  VARCHAR2(100) DEFAULT 'Carlos Mendoza' NOT NULL,
    CONSTRAINT fk_factura_cliente FOREIGN KEY (cliente_id) REFERENCES clientes(cliente_id)
);

COMMENT ON TABLE facturas IS 'Encabezado fiscal de ventas DTE validadas por el Ministerio de Hacienda';
COMMENT ON COLUMN facturas.codigo_generacion IS 'Identificador universal único (UUID) de la transacción DTE';

-- 5. TABLA 4: DETALLE_FACTURAS
-- Desglose de productos comprados. Almacena precio_unitario_historico para que 
-- los reportes del Administrador no se alteren si el producto cambia de precio en el futuro.
CREATE TABLE detalle_facturas (
    detalle_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura_id          NUMBER NOT NULL,
    producto_id         NUMBER NOT NULL,
    cantidad            NUMBER(8) NOT NULL CHECK (cantidad > 0),
    precio_unitario_historico NUMBER(10,2) NOT NULL, -- PRECIO HISTÓRICO CONGELADO AL MOMENTO DE VENTA
    subtotal_linea      NUMBER(12,2) NOT NULL,       -- (precio_unitario_historico * cantidad) / 1.13
    iva_linea           NUMBER(12,2) NOT NULL,       -- 13% IVA correspondiente a la línea
    CONSTRAINT fk_det_factura FOREIGN KEY (factura_id) REFERENCES facturas(factura_id) ON DELETE CASCADE,
    CONSTRAINT fk_det_producto FOREIGN KEY (producto_id) REFERENCES productos(producto_id)
);

COMMENT ON TABLE detalle_facturas IS 'Renglones de venta con precio histórico inalterable para auditorías fiscales';

-- 6. ÍNDICES DE RENDIMIENTO PARA ANALÍTICA EN TIEMPO REAL
CREATE INDEX idx_facturas_fecha ON facturas(fecha_hora);
CREATE INDEX idx_facturas_cliente ON facturas(cliente_id);
CREATE INDEX idx_det_factura ON detalle_facturas(factura_id);
CREATE INDEX idx_prod_stock ON productos(stock, stock_minimo);

-- 7. VISTA EJECUTIVA PARA EL ADMIN: RENDIMIENTO DE VENTAS E IVA (LIBRO F-07)
CREATE OR REPLACE VIEW v_resumen_fiscal_diario AS
SELECT 
    TRUNC(f.fecha_hora) AS fecha_emision,
    COUNT(f.factura_id) AS total_transacciones,
    SUM(f.subtotal_neto) AS base_imponible_gravada,
    SUM(f.iva_monto) AS total_iva_debito_fiscal,
    SUM(f.total_pagado) AS ingresos_brutos_totales,
    ROUND(AVG(f.total_pagado), 2) AS ticket_promedio
FROM facturas f
WHERE f.estado_hacienda = 'Transmitido con Éxito'
GROUP BY TRUNC(f.fecha_hora);

-- 8. VISTA DE PRODUCTOS CON STOCK CRÍTICO (ALERTAS AUTOMÁTICAS ADMIN)
CREATE OR REPLACE VIEW v_alertas_inventario_critico AS
SELECT 
    p.producto_id,
    p.sku,
    p.nombre,
    p.categoria,
    p.stock,
    p.stock_minimo,
    (p.stock_minimo - p.stock) AS unidades_a_reabastecer,
    CASE 
        WHEN p.stock = 0 THEN 'AGOTADO'
        WHEN p.stock <= p.stock_minimo THEN 'STOCK CRÍTICO'
        ELSE 'NORMAL'
    END AS estado_alerta
FROM productos p
WHERE p.stock <= p.stock_minimo;

